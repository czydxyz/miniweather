/* ========== TIM3 PWM 配置 ==========
   用于舵机控制（SG90 或类似 50Hz 舵机）
   引脚 PA6 (TIM3_CH1)
   
   频率计算：
     APB1 定时器时钟 = PCLK1 × 2 = 42MHz × 2 = 84MHz（APB1 分频≠1 时定时器自动×2）
     PSC = 83  → 84MHz / (83+1) = 1MHz（计数频率）
     ARR = 19999 → 1MHz / (19999+1) = 50Hz（周期 20ms）
     Pulse = 1500 → 1500/1MHz = 1.5ms（舵机中位，0°角度）
     
   舵机控制原理：
     0.5ms = 0°    (Pulse=500)
     1.0ms = 45°   (Pulse=1000)
     1.5ms = 90°   (Pulse=1500) ← 初始位置
     2.0ms = 135°  (Pulse=2000)
     2.5ms = 180°  (Pulse=2500)
*/
